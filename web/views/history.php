    <h3>Modern Enhancements</h3>
    <p>Recent years have seen significant modernization efforts:</p>
    <ul>
        <li><strong>Vulkan Renderer:</strong> Modern graphics API support</li>
        <li><strong>DirectX 12 Renderer:</strong> Windows-specific modern renderer</li>
        <li><strong>Physically-Based Rendering (PBR):</strong> Modern material system</li>
        <li><strong>Ray Tracing:</strong> Hardware-accelerated ray tracing support</li>
        <li><strong>Enhanced Networking:</strong> HTTP/2, WebSocket, connection pooling</li>
        <li><strong>Developer Tools:</strong> ImGui overlays, structured logging, memory safety tools</li>
        <li><strong>Code Quality:</strong> Modern C++ features, static analysis, unit tests</li>
    </ul>
    
    <h3>Current State</h3>
    <p>Today, id Tech 3 continues to evolve through community efforts, with modern renderers, enhanced networking, improved developer tools, and ongoing support for both classic and new content. The engine remains relevant for:</p>
    <ul>
        <li>Classic Quake III Arena gameplay</li>
        <li>New game development projects</li>

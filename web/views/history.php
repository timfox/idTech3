<div class="section">
    <h2>Open Source Release (2005)</h2>
    
    <h3>The GPL Release</h3>
    <p><strong>August 19, 2005</strong> - id Software released the source code of id Tech 3 under the <strong>GNU General Public License version 2.0</strong>. This landmark decision followed id Software's tradition of open-sourcing their engines after a period of commercial use.</p>
    
    <h3>Impact of Open Source</h3>
    <ul>
        <li><strong>Community Development:</strong> Enabled community-driven improvements and ports</li>
        <li><strong>Educational Value:</strong> Became a valuable learning resource for game developers</li>
        <li><strong>Extended Lifespan:</strong> Allowed the engine to evolve beyond its commercial lifecycle</li>
        <li><strong>Modding Renaissance:</strong> Facilitated deeper modifications and total conversions</li>
    </ul>
    
    <h3>Notable Open Source Projects</h3>
    <ul>
        <li><strong>ioquake3</strong> - Clean, maintained fork focusing on bug fixes and compatibility</li>
        <li><strong>OpenArena</strong> - Free, open-source game using id Tech 3</li>
        <li><strong>ET: Legacy</strong> - Modern continuation of Wolfenstein: Enemy Territory</li>
        <li><strong>Quake3e</strong> - Enhanced version with modern features</li>
    </ul>
</div>


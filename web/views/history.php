<div class="section">
    <h2>Original Development (1996-1999)</h2>
    
    <h3>Conception and Design</h3>
    <p>Following the success of Quake and Quake II, id Software began development on what would become id Tech 3 in 1996. The engine was specifically designed for <strong>Quake III Arena</strong>, which marked a shift from single-player focused games to competitive multiplayer arena combat.</p>
    
    <p>The decision to focus on multiplayer was revolutionary at the time. While Quake and Quake II had strong multiplayer components, they were primarily single-player games. Quake III Arena would be id Software's first game designed exclusively for multiplayer competition, reflecting the growing importance of competitive gaming.</p>
    
    <h3>Key Design Goals</h3>
    <ul>
        <li><strong>Multiplayer Focus:</strong> Optimized for low-latency, competitive multiplayer gameplay</li>
        <li><strong>Visual Quality:</strong> Advanced graphics capabilities for the era</li>
        <li><strong>Modding Support:</strong> Built-in support for extensive community modifications</li>
        <li><strong>Cross-Platform:</strong> Support for Windows, Linux, and Macintosh</li>
        <li><strong>Performance:</strong> Smooth 60+ FPS gameplay on hardware of the era</li>
        <li><strong>Fair Play:</strong> Server-side authoritative gameplay to prevent cheating</li>
    </ul>
    
    <h3>Development Team</h3>
    <p>The engine was primarily developed by:</p>
    <ul>
        <li><strong>John Carmack</strong> - Lead programmer and engine architect, designed the shader system and QVM architecture</li>
        <li><strong>Tim Willits</strong> - Level design and game direction, later became id Software studio director</li>
        <li><strong>Graeme Devine</strong> - Game programming and AI systems</li>
        <li><strong>Paul Steed</strong> - Character modeling and animation, created iconic Quake III Arena characters</li>
        <li><strong>Kevin Cloud</strong> - Art direction and level design</li>
        <li><strong>Christian Antkow</strong> - Level design</li>
    </ul>
    
    <h3>Development Challenges</h3>
    <p>The development of id Tech 3 faced several significant challenges:</p>
    <ul>
        <li><strong>Hardware Limitations:</strong> Designing for hardware that didn't yet exist (3D accelerators were new)</li>
        <li><strong>Network Latency:</strong> Creating fair multiplayer gameplay over internet connections</li>
        <li><strong>Cross-Platform:</strong> Maintaining consistency across Windows, Linux, and Macintosh</li>
        <li><strong>Shader System:</strong> Pioneering shader-based rendering before it was standardized</li>
        <li><strong>Performance:</strong> Achieving smooth gameplay while pushing graphical boundaries</li>
    </ul>
</div>

<div class="section">
    <h2>Release and Impact (1999-2005)</h2>
    
    <h3>Quake III Arena Release</h3>
    <p><strong>December 2, 1999</strong> - Quake III Arena was released, showcasing id Tech 3's capabilities:</p>
    <ul>
        <li>Fast-paced arena combat</li>
        <li>Advanced graphics with curved surfaces and dynamic lighting</li>
        <li>Robust networking for competitive play</li>
        <li>Extensive modding capabilities</li>
    </ul>
    
    <h3>Technical Innovations</h3>
    <div class="feature-list">
        <h4>Graphics Technology</h4>
        <ul>
            <li><strong>Shader System:</strong> Introduced a shader-based rendering system using vertex and pixel shaders</li>
            <li><strong>Bézier Patches:</strong> Spline-based curved surfaces for smoother environments</li>
            <li><strong>Simulated Bump Mapping:</strong> Surface detailing without full normal mapping hardware</li>
            <li><strong>Dynamic Lighting:</strong> Per-pixel lighting calculations</li>
            <li><strong>Lightmaps:</strong> Pre-computed lighting for static geometry</li>
        </ul>
        
        <h4>Architecture Innovations</h4>
        <ul>
            <li><strong>Virtual Machine (QVM):</strong> Platform-independent bytecode for game logic, effects, and UI</li>
            <li><strong>Snapshot System:</strong> Efficient UDP-based networking for multiplayer</li>
            <li><strong>Client-Server Architecture:</strong> Authoritative server with client-side prediction</li>
            <li><strong>Lag Compensation:</strong> Server-side hit detection for fair gameplay</li>
        </ul>
    </div>
    
    <h3>Commercial Success</h3>
    <p>Quake III Arena became one of the most successful competitive multiplayer games of its era, establishing itself as a staple of esports and competitive gaming communities worldwide.</p>
</div>


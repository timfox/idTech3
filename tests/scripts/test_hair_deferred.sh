#!/usr/bin/env bash
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
H="$ROOT/renderers/vulkan/extensions/scaffold/vk_hair_deferred.c"
HH="$ROOT/renderers/vulkan/extensions/scaffold/vk_hair_deferred.h"
DOC="$ROOT/docs/HAIR_DEFERRED.md"

VIS_SHADER="$ROOT/renderers/vulkan/shaders/glsl/hair_deferred/hair_visibility_atomic.comp"

grep -q 'vkHairBundle_t' "$HH"
grep -q 'visibilityBits' "$HH"
grep -q 'r_hairDeferred' "$H"
grep -q 'hair_deferred_status' "$H"
grep -q 'vk.forward_plus.tile_buffer' "$H"
